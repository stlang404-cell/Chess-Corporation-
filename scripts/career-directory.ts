/** Generates docs/CAREER_DIRECTORY.md from the live career data (never hand-edited). */
import { writeFileSync } from 'node:fs';
import { FAMILIES, STEPS, GM_TITLES, INSTITUTIONS, STAGE_ARENAS } from '../src/game/careerData';
import { rankInfo, rankLine, ratingGate, seriesLength, salary, firstRankOfTitle, arenaInfo, AUTHORED_RANKS, AUTHORED_ARENA_COUNT, authoredTitleCount, authoredGradeCount, meritNeeded, INST_START } from '../src/game/career';

const L: string[] = [];
L.push('# SEVEN Career Directory', '', '*Generated by `scripts/career-directory.ts` from the game data. Gates follow the calibrated bot scale at generation time.*', '');
L.push(`**${authoredTitleCount()} authored titles · ${authoredGradeCount().toLocaleString('en-US')} authored grades · ${AUTHORED_ARENA_COUNT} authored arenas · unbounded procedural continuation.**`, '');
L.push('## 1. Seniority steps (shared by every job family)', '', '| Step | Seniority | Scope | Grades | Major? | First rank | Rating gate | Salary at entry |', '|---|---|---|---|---|---|---|---|');
STEPS.forEach((s, i) => {
  const n = firstRankOfTitle(i);
  L.push(`| ${i} | ${s.name} | ${s.scope} | ${s.grades} | ${s.major ? `Bo${seriesLength(n)}` : ''} | ${n} | ${ratingGate(n) || '—'} | $${salary(n)} |`);
});
L.push('', '## 2. Job families (functional titles by step)', '');
for (const f of FAMILIES) {
  L.push(`### ${f.name}`, '', f.titles.map((t, i) => `${i}. ${t}`).join(' · '), '');
}
L.push('## 3. General management — Seven Meridian Corporation (Tokyo)', '', '| Title | Scope | First rank | Gate | Series |', '|---|---|---|---|---|');
GM_TITLES.forEach((g, i) => {
  const n = firstRankOfTitle(STEPS.length + i);
  L.push(`| ${g.title} | ${g.scope} | ${n} | ${ratingGate(n)} | Bo${seriesLength(n)} |`);
});
L.push('', '## 4. Institutions (authored)', '', '| # | Institution | City | Headquarters | Sector | Scale class | President from rank | CEO from rank | Gate |', '|---|---|---|---|---|---|---|---|---|');
INSTITUTIONS.forEach((inst, i) => {
  const p = INST_START + i * 10;
  L.push(`| ${i + 1} | ${inst.name} | ${inst.city} | ${inst.hq} | ${inst.sector} | ${inst.scale} | ${p} | ${p + 5} | ${ratingGate(p)} |`);
});
L.push('', '## 5. Arenas (authored)', '', '| # | Arena | Kanji | First rank |', '|---|---|---|---|');
for (let i = 0; i < AUTHORED_ARENA_COUNT; i++) {
  const a = arenaInfo(i);
  L.push(`| ${i + 1} | ${a.name} | ${a.kanji} | ${a.firstRank} |`);
}
L.push('', `(${STAGE_ARENAS.length} floors of the home company, then the headquarters of each institution.)`);
L.push('', '## 6. Beyond the authored path (procedural sample)', '', '| Rank | Appointment | Merit to complete | Salary |', '|---|---|---|---|');
for (const n of [AUTHORED_RANKS, AUTHORED_RANKS + 5, AUTHORED_RANKS + 10, AUTHORED_RANKS + 100, AUTHORED_RANKS + 1000, 10_000, 100_000, 1_000_000, 10 ** 9, Number.MAX_SAFE_INTEGER]) {
  L.push(`| ${n.toLocaleString('en-US')} | ${rankLine(n)} (${rankInfo(n).appointment.split(' · ')[1] ?? ''}) | ${meritNeeded(n).toLocaleString('en-US')} | $${salary(n).toLocaleString('en-US')} |`);
}
L.push('', 'Every rank is a pure function of its number and the job family; promotions store the title text at the time they were earned.', '');
writeFileSync('docs/CAREER_DIRECTORY.md', L.join('\n'));
console.log(`wrote docs/CAREER_DIRECTORY.md (${L.length} lines)`);
