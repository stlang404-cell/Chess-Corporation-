/**
 * Fit bot ratings from the calibration tournament (research/calib/*.jsonl).
 * Bradley–Terry / Elo maximum likelihood (draws = half points), anchored at
 * tier 0 = 400. Standard errors from the observed Fisher information.
 * Style offsets: each style vs balanced at the same tier, converted to Elo and
 * averaged over the tiers tested (assumes a constant offset across tiers).
 * Writes src/engine/calibration.ts and research/calibration-report.md.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

interface G { a: string; b: string; scoreA: number }
const games: G[] = [];
for (const f of readdirSync('research/calib')) {
  if (!f.endsWith('.jsonl')) continue;
  for (const line of readFileSync('research/calib/' + f, 'utf8').split('\n')) if (line.trim()) games.push(JSON.parse(line));
}
const tierGames = games.filter((g) => g.a.endsWith(':balanced') && g.b.endsWith(':balanced'));
const tiers = [...new Set(tierGames.flatMap((g) => [g.a, g.b]))].map((x) => +x.split(':')[0]).sort((a, b) => a - b);
const N = Math.max(...tiers) + 1;
const r = new Array(N).fill(0).map((_, i) => i * 150);
const C = Math.LN10 / 400;
const E = (d: number) => 1 / (1 + Math.pow(10, -d / 400));
for (let it = 0; it < 20000; it++) {
  const grad = new Array(N).fill(0);
  for (const g of tierGames) {
    const a = +g.a.split(':')[0], b = +g.b.split(':')[0];
    const e = E(r[a] - r[b]);
    grad[a] += g.scoreA - e;
    grad[b] -= g.scoreA - e;
  }
  // weak prior toward a smooth ladder keeps unobserved / perfect-score pairs finite
  for (let i = 1; i < N; i++) {
    const d = r[i] - r[i - 1];
    grad[i] -= (d - 200) / 400 ** 2 * 4;
    grad[i - 1] += (d - 200) / 400 ** 2 * 4;
  }
  let m = 0;
  for (let i = 1; i < N; i++) {
    r[i] += grad[i] * 8;
    m = Math.max(m, Math.abs(grad[i]));
  }
  if (m < 1e-6) break;
}
const anchor = 400 - r[0];
const ratings = r.map((x) => Math.round(x + anchor));
// standard errors: diagonal of Fisher information (approximate, ignores covariance)
const info = new Array(N).fill(0);
for (const g of tierGames) {
  const a = +g.a.split(':')[0], b = +g.b.split(':')[0];
  const e = E(r[a] - r[b]);
  info[a] += C * C * e * (1 - e);
  info[b] += C * C * e * (1 - e);
}
const se = info.map((v, i) => (i === 0 ? 0 : Math.round(1 / Math.sqrt(Math.max(v, 1e-6)))));
const rd = se.map((s) => Math.max(40, Math.min(150, s)));

// style offsets
const styles: Record<string, number[]> = {};
const styleRows: string[] = [];
for (const g of games) {
  const [ta, sa] = g.a.split(':');
  const [tb, sb] = g.b.split(':');
  if (ta !== tb || sb !== 'balanced' || sa === 'balanced') continue;
  (styles[`${sa}@${ta}`] ??= []).push(g.scoreA);
}
const offsets: Record<string, number> = { balanced: 0 };
const per: Record<string, number[]> = {};
for (const [k, v] of Object.entries(styles)) {
  const [s, t] = k.split('@');
  const p = Math.min(0.95, Math.max(0.05, v.reduce((a, b) => a + b, 0) / v.length));
  const off = 400 * Math.log10(p / (1 - p));
  (per[s] ??= []).push(off);
  styleRows.push(`| ${s} | ${t} | ${v.length} | ${(p * 100).toFixed(1)}% | ${off >= 0 ? '+' : ''}${Math.round(off)} |`);
}
for (const [s, v] of Object.entries(per)) offsets[s] = Math.round(v.reduce((a, b) => a + b, 0) / v.length);

const date = new Date().toISOString().slice(0, 10);
writeFileSync(
  'src/engine/calibration.ts',
  `/**
 * Measured bot strengths. GENERATED by scripts/fit-ratings.ts from the tier
 * round-robin in research/calib — do not hand-edit. Scale anchored so that
 * tier 0 = 400. This is the SEVEN rating scale; it is NOT a FIDE rating.
 */
export const CALIBRATION = {
  generated: 'measured ${date}',
  games: ${games.length},
  tierRatings: ${JSON.stringify(ratings)},
  tierRd: ${JSON.stringify(rd)},
  styleOffsets: ${JSON.stringify(offsets)} as Record<string, number>,
};
`,
);

// pairwise table
const pairs = new Map<string, number[]>();
for (const g of tierGames) {
  const k = `${g.a.split(':')[0]} vs ${g.b.split(':')[0]}`;
  (pairs.get(k) ?? pairs.set(k, []).get(k)!).push(g.scoreA);
}
const lines = [
  `# Bot calibration report (generated ${date})`,
  '',
  `Games: ${games.length} (${tierGames.length} tier-vs-tier, ${games.length - tierGames.length} style-vs-balanced).`,
  '',
  '## Fitted tier ratings (anchor: tier 0 = 400)',
  '',
  '| Tier | Rating | ± (1 s.e.) |',
  '|---|---|---|',
  ...ratings.map((x, i) => `| ${i} | ${x} | ${i === 0 ? 'anchor' : se[i]} |`),
  '',
  '## Pairwise results (score of the first-named tier)',
  '',
  '| Pairing | Games | Score | Predicted by fit |',
  '|---|---|---|---|',
  ...[...pairs.entries()].map(([k, v]) => {
    const [a, b] = k.split(' vs ').map(Number);
    return `| ${k} | ${v.length} | ${((v.reduce((x, y) => x + y, 0) / v.length) * 100).toFixed(1)}% | ${(E(ratings[a] - ratings[b]) * 100).toFixed(1)}% |`;
  }),
  '',
  '## Style offsets (style vs balanced at the same tier)',
  '',
  '| Style | Tier | Games | Score | Elo offset |',
  '|---|---|---|---|---|',
  ...styleRows,
  '',
  `Applied offsets (mean over tiers): ${JSON.stringify(offsets)}`,
  '',
];
writeFileSync('research/calibration-report.md', lines.join('\n'));
