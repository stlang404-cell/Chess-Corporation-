import 'fake-indexeddb/auto';
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { migrate, newSave, UNTIMED, SAVE_VERSION, type ActiveMatch } from '../src/game/state';
import { isUntimed, clocksAfterMove, hasFlagged, initialClocks, botThinkCapMs } from '../src/game/clock';
import { settleMatch } from '../src/game/settle';
import { writeSave, loadSave } from '../src/game/storage';
import { replay } from '../src/engine/game';
import { OFFICIAL } from '../src/engine/rules';

const mem = new Map<string, string>();
(globalThis as any).localStorage = {
  getItem: (k: string) => mem.get(k) ?? null,
  setItem: (k: string, v: string) => void mem.set(k, v),
  removeItem: (k: string) => void mem.delete(k),
};

function untimedMatch(moves: string[] = []): ActiveMatch {
  return {
    id: 'u1',
    kind: 'ranked',
    opponent: { id: 7, tier: 5, style: 'balanced', rating: 1100, rd: 60, name: 'Bot' },
    playerColor: 0,
    moves,
    clocks: initialClocks(UNTIMED),
    tc: UNTIMED,
    startedAt: 0,
    seed: 1,
    drawOffers: 0,
    undos: 0,
  };
}

describe('untimed chess', () => {
  it('untimed is the default for new careers and has no clocks', () => {
    const s = newSave(0);
    expect(s.settings.tc).toBe(UNTIMED);
    expect(initialClocks(UNTIMED)).toBeNull();
    expect(isUntimed(untimedMatch())).toBe(true);
  });
  it('never flags, however long a player thinks', () => {
    const m = untimedMatch(['d2d4', 'e6e4']);
    for (const elapsed of [0, 60_000, 3_600_000, 30 * 86_400_000, Number.MAX_SAFE_INTEGER]) {
      expect(hasFlagged(m, 0, elapsed)).toBe(false);
      expect(hasFlagged(m, 1, elapsed)).toBe(false);
    }
    expect(clocksAfterMove(m, 0, 10_000_000)).toBeNull();
  });
  it('timed games still flag and add increments', () => {
    const m: ActiveMatch = { ...untimedMatch(['d2d4']), tc: '5+3', clocks: [300_000, 300_000] };
    expect(isUntimed(m)).toBe(false);
    expect(hasFlagged(m, 1, 299_999)).toBe(false);
    expect(hasFlagged(m, 1, 300_000)).toBe(true);
    expect(clocksAfterMove(m, 1, 10_000)).toEqual([300_000, 293_000]);
  });
  it('AI thinking is bounded independently of the player clock', () => {
    const m = untimedMatch();
    expect(botThinkCapMs(m, 1, 'standard')).toBe(4000);
    expect(botThinkCapMs(m, 1, 'strong')).toBe(10000);
    const timed: ActiveMatch = { ...m, tc: '3+2', clocks: [5000, 5000] };
    expect(botThinkCapMs(timed, 1, 'strong')).toBeLessThan(2000);
  });
  it('an untimed game in progress survives save/reload and stays untimed', async () => {
    const s = newSave(0);
    s.active = untimedMatch(['d2d4', 'e6e4', 'b1c3']);
    await writeSave(s);
    const { save } = await loadSave();
    expect(save!.active!.clocks).toBeNull();
    expect(save!.active!.moves).toEqual(['d2d4', 'e6e4', 'b1c3']);
    expect(replay(OFFICIAL, { moves: save!.active!.moves }).side).toBe(1);
  });
  it('untimed games settle exactly like timed ones (checkmate, resignation, draws)', () => {
    let s = newSave(0);
    for (const [i, term, score] of [
      [0, 'checkmate', 1],
      [1, 'resignation', 0],
      [2, 'repetition', 0.5],
      [3, 'stalemate', 0.5],
    ] as const) {
      const m = { ...untimedMatch(new Array(40).fill('a2a3')), id: 'g' + i, finished: { score, termination: term, endedAt: 1 } } as ActiveMatch;
      s = settleMatch(s, m, i).save;
    }
    expect(s.stats.rated).toMatchObject({ g: 4, w: 1, d: 2, l: 1 });
  });
});

describe('v0.1 save migration (real fixture generated by the v0.1 code)', () => {
  const raw = JSON.parse(readFileSync('tests/fixtures/save-v0.1.json', 'utf8'));
  const m = migrate(raw);
  it('upgrades the schema version and switches the default to untimed', () => {
    expect(raw.version).toBe(1);
    expect(m.version).toBe(SAVE_VERSION);
    expect(m.settings.tc).toBe(UNTIMED);
  });
  it('preserves rating, history, dollars, purchases and achievements', () => {
    expect(m.rating).toEqual(raw.rating);
    expect(m.peakRating).toBe(raw.peakRating);
    expect(m.history.length).toBe(raw.history.length);
    expect(m.wallet).toEqual(raw.wallet);
    expect(m.owned).toEqual(expect.arrayContaining(raw.owned));
    expect(m.equipped.board).toBe('board.washi');
    expect(Object.keys(m.achievements)).toEqual(Object.keys(raw.achievements));
    expect(m.settled).toEqual(raw.settled);
    expect(m.hq.floors).toBe(2);
  });
  it('keeps the timed game in progress timed, with its clocks', () => {
    expect(m.active!.tc).toBe('5+3');
    expect(m.active!.clocks).toEqual([250000, 280000]);
    expect(isUntimed(m.active!)).toBe(false);
  });
  it('can keep playing: settling a new match after migration works', () => {
    const next = settleMatch(m, { ...untimedMatch(new Array(30).fill('a2a3')), id: 'after', finished: { score: 1, termination: 'checkmate', endedAt: 2 } }, 5);
    expect(next.duplicate).toBe(false);
    expect(next.save.stats.rated.g).toBe(raw.stats.rated.g + 1);
  });
  it('is idempotent', () => {
    expect(migrate(JSON.parse(JSON.stringify(m)))).toEqual(m);
  });
});
